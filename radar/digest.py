"""Daily Markdown digest: the most important AI stories, grouped by theme."""

import re
from datetime import datetime, timedelta

import pandas as pd

from radar.config import DIGEST_SIZE, THEMES, UNCLASSIFIED_LABEL, WINDOW_HOURS

_MARKDOWN_SPECIAL = re.compile(r"([\\`*_\[\]<>])")


def escape_md(text: str) -> str:
    return _MARKDOWN_SPECIAL.sub(r"\\\1", text)


def recent_posts(df: pd.DataFrame, now: datetime, window_hours: int = WINDOW_HOURS) -> pd.DataFrame:
    created = pd.to_datetime(df["created_at"], utc=True)
    return df[created >= now - timedelta(hours=window_hours)]


def select_top(df: pd.DataFrame, now: datetime, window_hours: int = WINDOW_HOURS,
               limit: int = DIGEST_SIZE) -> pd.DataFrame:
    """Top ``limit`` stories of the window, ranked by points + comments."""
    recent = recent_posts(df, now, window_hours).copy()
    recent["importance"] = recent["score"] + recent["num_comments"]
    return recent.sort_values(["importance", "score", "id"], ascending=False).head(limit)


def _render_post(post) -> list[str]:
    domain = f" ({post.domain})" if post.domain else ""
    lines = [f"- **[{escape_md(post.title)}]({post.url})**{domain}"]
    if post.summary:
        lines[-1] += "\\"
        lines.append(f"  {escape_md(post.summary)}")
    lines[-1] += "\\"
    lines.append(
        f"  {post.score} points · {post.num_comments} comments · [discussion]({post.hn_url})"
    )
    return lines


def render_digest(top: pd.DataFrame, now: datetime, total: int,
                  window_hours: int = WINDOW_HOURS) -> str:
    lines = [f"# AI News Radar — {now:%Y-%m-%d}", ""]
    if top.empty:
        lines += [f"No AI-related stories were found on Hacker News in the {window_hours} hours "
                  f"to {now:%H:%M} UTC.", ""]
        return "\n".join(lines)

    lines += [
        f"Top {len(top)} of {total} AI-related stories posted on Hacker News in the "
        f"{window_hours} hours to {now:%H:%M} UTC, ranked by points + comments and grouped by theme.",
        "",
    ]
    sections = list(THEMES.items()) + [("", UNCLASSIFIED_LABEL)]
    for slug, label in sections:
        posts = top[top["theme"] == slug]
        if posts.empty:
            continue
        lines += [f"## {label}", ""]
        for post in posts.itertuples(index=False):
            lines += _render_post(post)
        lines.append("")
    lines += ["---", "",
              "*Generated by [ai-news-radar](../README.md) from the Hacker News API; "
              "themes and summaries by Gemini.*", ""]
    return "\n".join(lines)
