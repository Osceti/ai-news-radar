"""Daily Markdown digest: the most important AI stories of one UTC day, by theme."""

import re
from datetime import date, datetime, time, timedelta, timezone

import pandas as pd

from radar.config import DIGEST_SIZE, THEMES, UNCLASSIFIED_LABEL

_MARKDOWN_SPECIAL = re.compile(r"([\\`*_\[\]<>])")


def escape_md(text: str) -> str:
    return _MARKDOWN_SPECIAL.sub(r"\\\1", text)


def previous_day(now: datetime) -> date:
    """The last complete UTC day before ``now``: the day a run should report on."""
    return (now.astimezone(timezone.utc) - timedelta(days=1)).date()


def posts_on(df: pd.DataFrame, day: date) -> pd.DataFrame:
    """Stories posted on ``day``, from 00:00 to 24:00 UTC."""
    start = datetime.combine(day, time(), tzinfo=timezone.utc)
    created = pd.to_datetime(df["created_at"], utc=True)
    return df[(created >= start) & (created < start + timedelta(days=1))]


def select_top(df: pd.DataFrame, day: date, limit: int = DIGEST_SIZE) -> pd.DataFrame:
    """Top ``limit`` stories posted on ``day``, ranked by points + comments."""
    stories = posts_on(df, day).copy()
    stories["importance"] = stories["score"] + stories["num_comments"]
    return stories.sort_values(["importance", "score", "id"], ascending=False).head(limit)


def _render_post(post) -> list[str]:
    domain = f" ({post.domain})" if post.domain else ""
    lines = [f"- **[{escape_md(post.title)}]({post.url})**{domain}"]
    if post.summary:
        lines[-1] += "\\"
        lines.append(f"  {escape_md(post.summary)}")
    lines[-1] += "\\"
    lines.append(
        f"  {post.score} points · {post.num_comments} comments · [discussion]({post.hn_url})"
    )
    return lines


def render_digest(top: pd.DataFrame, day: date, total: int) -> str:
    lines = [f"# AI News Radar — {day:%Y-%m-%d}", ""]
    when = f"{day:%A} {day.day} {day:%B %Y} (UTC)"
    if top.empty:
        lines += [f"No AI-related stories were found on Hacker News on {when}.", ""]
        return "\n".join(lines)

    lines += [
        f"Top {len(top)} of {total} AI-related stories posted on Hacker News on {when}, "
        "ranked by points + comments and grouped by theme.",
        "",
    ]
    sections = list(THEMES.items()) + [("", UNCLASSIFIED_LABEL)]
    for slug, label in sections:
        posts = top[top["theme"] == slug]
        if posts.empty:
            continue
        lines += [f"## {label}", ""]
        for post in posts.itertuples(index=False):
            lines += _render_post(post)
        lines.append("")
    lines += ["---", "",
              "*Generated by [ai-news-radar](../README.md) from the Hacker News API; "
              "themes and summaries by Gemini.*", ""]
    return "\n".join(lines)
